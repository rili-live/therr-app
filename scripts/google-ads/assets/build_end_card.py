#!/usr/bin/env python3
"""Build the 9:16 end card for the Friends with Habits video ads.

The end card is the last ~2s of a video ad: logo, name, tagline and the Play
badge. It is built here rather than generated by a video model because it is
the one frame where every pixel has to be exact — AI models misspell text,
approximate logos, and redraw the Play badge, which Google's badge guidelines
forbid modifying.

Two variants:
  solid    — brand-purple card, usable on its own.
  overlay  — transparent PNG with a soft purple scrim, laid over a blurred
             freeze of the video's last frame so the scene stays visible
             behind the text.

Content sits between 14% from the top and 35% from the bottom, clear of the
Reels / Shorts UI overlays.

Reuses the logo, palette, font and Chrome renderer from build_frames.py so the
end card and the static ad frames are the same brand.

Usage:
    python3 scripts/google-ads/assets/build_end_card.py [--tagline TEXT] [--out DIR]
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_frames import (  # noqa: E402
    AMBER, CHROME, CREAM, PURPLE, PURPLE_DEEP, REPO_ROOT, data_uri, logo_png,
)

OUT_DIR = Path(__file__).resolve().parent / "video"
# Official badge, unmodified, from https://play.google.com/intl/en_us/badges/
# (en_badge_web_generic.png). Its transparent padding is part of the badge's
# required clear space, so it is scaled as-is, never cropped.
BADGE_PATH = OUT_DIR / "google-play-badge-en.png"

WIDTH, HEIGHT = 1080, 1920
TAGLINE = "Evolve your life."


def build_html(variant: str, logo_uri: str, badge_uri: str, tagline: str) -> str:
    if variant == "solid":
        background = (
            f"radial-gradient(110% 70% at 50% 38%, #4A365F 0%, {PURPLE} 48%, {PURPLE_DEEP} 100%)"
        )
        shadow = "none"
    else:
        # Scrim only: dark enough that cream text holds over a bright fire,
        # light enough that the scene still reads through it.
        background = (
            "radial-gradient(85% 55% at 50% 40%, rgba(42,29,56,0.72) 0%, "
            "rgba(42,29,56,0.55) 55%, rgba(42,29,56,0.35) 100%)"
        )
        shadow = "0 4px 24px rgba(0,0,0,0.45)"

    return f"""<!doctype html>
<html><head><meta charset="utf-8">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Lexend:wght@400;600;800&display=swap" rel="stylesheet">
<style>
  *, *::before, *::after {{ box-sizing: border-box; }}
  html {{ background: transparent; }}
  body {{
    margin: 0; width: {WIDTH}px; height: {HEIGHT}px; overflow: hidden;
    background: {background};
    font-family: 'Lexend', -apple-system, BlinkMacSystemFont, 'Helvetica Neue', sans-serif;
    color: {CREAM};
  }}
  /* Safe zone: 14% top (269px), 35% bottom (672px). */
  .safe {{
    position: absolute; left: 80px; right: 80px; top: 269px; bottom: 672px;
    display: flex; flex-direction: column; align-items: center; justify-content: center;
    text-align: center;
  }}
  .logo {{ width: 220px; height: 220px; display: block;
           filter: drop-shadow({shadow if shadow != 'none' else '0 0 0 transparent'}); }}
  h1 {{
    margin: 36px 0 0; font-weight: 800; font-size: 88px; line-height: 1.02;
    letter-spacing: -0.035em; color: #fff; text-shadow: {shadow};
  }}
  .tagline {{
    margin: 22px 0 0; font-weight: 600; font-size: 54px; color: {AMBER};
    letter-spacing: -0.01em; text-shadow: {shadow};
  }}
  .badge {{ width: 470px; display: block; margin-top: 44px; }}
</style></head>
<body>
  <div class="safe">
    <img class="logo" src="{logo_uri}" alt="">
    <h1>Friends with<br>Habits</h1>
    <p class="tagline">{tagline}</p>
    <img class="badge" src="{badge_uri}" alt="Get it on Google Play">
  </div>
</body></html>"""


def shoot(html: str, out: Path, workdir: Path) -> None:
    page = workdir / f"{out.stem}.html"
    page.write_text(html)
    subprocess.run(
        [
            CHROME, "--headless", "--disable-gpu", "--hide-scrollbars",
            # Transparent canvas, so the overlay variant keeps its alpha.
            "--default-background-color=00000000",
            f"--screenshot={out}", f"--window-size={WIDTH},{HEIGHT}",
            "--virtual-time-budget=4000",
            f"file://{page}",
        ],
        check=True, capture_output=True,
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--tagline", default=TAGLINE)
    args = parser.parse_args()

    if not Path(CHROME).exists():
        print(f"Chrome not found at {CHROME}. Install it, or edit CHROME.", file=sys.stderr)
        return 1

    args.out.mkdir(parents=True, exist_ok=True)
    logo_uri = data_uri(logo_png(), "image/png")
    badge_uri = data_uri(BADGE_PATH.read_bytes(), "image/png")

    workdir = Path(tempfile.mkdtemp(prefix="fwh-endcard-"))
    try:
        for variant in ("solid", "overlay"):
            out = args.out / f"endcard-{WIDTH}x{HEIGHT}-{variant}.png"
            shoot(build_html(variant, logo_uri, badge_uri, args.tagline), out, workdir)
            print(f"  wrote {out.relative_to(REPO_ROOT)}")
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
